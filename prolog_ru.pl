:- dynamic кэш/6.

штраф(Режим, Ключ, Вес) :-
    вес(Режим, Ключ, Вес),
    !.
штраф(_, Ключ, Вес) :-
    вес(по_умолчанию, Ключ, Вес).

разбить(Слова, Ширина, Режим, Строки, Оценка, Отчет) :-
    retractall(кэш(_, _, _, _, _, _)),
    лучшее(Слова, Ширина, Режим, Строки, Оценка, Сырой),
    пронумеровать(Сырой, 1, Отчет).

лучшее(Слова, Ширина, Режим, Строки, Оценка, Отчет) :-
    кэш(Слова, Ширина, Режим, Строки, Оценка, Отчет),
    !.

лучшее([], Ширина, Режим, [], Оценка, []) :-
    !,
    пустая_оценка(Режим, Ширина, Оценка),
    assertz(кэш([], Ширина, Режим, [], Оценка, [])).

лучшее(Слова, Ширина, Режим, Строки, Оценка, Отчет) :-
    findall(Оц-вариант(Стр, Отч), вариант(Слова, Ширина, Режим, Стр, Оц, Отч), Список),
    Список \= [],
    keysort(Список, [Оценка-вариант(Строки, Отчет)|_]),
    assertz(кэш(Слова, Ширина, Режим, Строки, Оценка, Отчет)).

вариант(Слова, Ширина, Режим, [Строка|ОстСтроки], Оценка, [ОтчетСтр|ОстОтчет]) :-
    набрать(Слова, Ширина, Строка, Остаток),
    лучшее(Остаток, Ширина, Режим, ОстСтроки, ОстОценка, ОстОтчет),
    оценить_строку(Строка, ОстСтроки, Ширина, Режим, 0, ОтчетСтр, Крит, Линг, Пункт, Типо),
    добавить_строку(Режим, Крит, Линг, Пункт, Типо, ОстОценка, Оценка).

набрать(Слова, Ширина, Строка, Остаток) :-
    набор(Слова, Ширина, [], 0, Строка, Остаток).

набор([Слово|Хвост], Ширина, Взято, Длина, Строка, Хвост) :-
    плюс_длина(Взято, Слово, Длина, Длина2),
    Длина2 =< Ширина,
    reverse([Слово|Взято], Строка).

набор([Слово|Хвост], Ширина, Взято, Длина, Строка, Остаток) :-
    плюс_длина(Взято, Слово, Длина, Длина2),
    Длина2 =< Ширина,
    набор(Хвост, Ширина, [Слово|Взято], Длина2, Строка, Остаток).

плюс_длина([], Слово, _, Длина) :-
    !,
    atom_length(Слово, Длина).

плюс_длина([Пред|_], Слово, Длина, Длина2) :-
    atom_length(Слово, ДлинаСлова),
    пробел(Пред, Слово, Пробел),
    Длина2 is Длина + Пробел + ДлинаСлова.

пустая_оценка(Режим, Ширина, Оценка) :-
    собрать_оценку(Режим, Ширина, 0, 0, 0, 0, 0, Оценка).

добавить_строку(Режим, Крит, Линг, Пункт, Типо, оценка(ОстКрит, ОстСтрок, ОстЛинг, ОстПункт, ОстТипо, _), Оценка) :-
    Крит2 is Крит + ОстКрит,
    Строк2 is ОстСтрок + 1,
    Линг2 is Линг + ОстЛинг,
    Пункт2 is Пункт + ОстПункт,
    Типо2 is Типо + ОстТипо,
    собрать_оценку(Режим, _, Крит2, Строк2, Линг2, Пункт2, Типо2, Оценка).

собрать_оценку(Режим, _, Крит, ЧислоСтрок, Линг, Пункт, Типо, Оценка) :-
    штраф(Режим, критич, ВесКрит),
    штраф(Режим, число_строк, ВесСтроки),
    Итог is Крит * ВесКрит + ЧислоСтрок * ВесСтроки + Линг + Пункт + Типо,
    Оценка = оценка(Крит, ЧислоСтрок, Линг, Пункт, Типо, Итог).

пронумеровать([], _, []).

пронумеровать([строка(_, Стр, Длина, Плох, Крит, Линг, Пункт, Прич)|Хвост], Номер, [строка(Номер, Стр, Длина, Плох, Крит, Линг, Пункт, Прич)|Рез]) :-
    Номер2 is Номер + 1,
    пронумеровать(Хвост, Номер2, Рез).

оценить_строку(Стр, Хвост, Ширина, Режим, Номер, строка(Номер, Стр, длина(Длина), плохость(Плох), крит(Крит), линг(Линг), пункт(Пункт), причины(Причины)), Крит, Линг, Пункт, Типо) :-
    длина_строки(Стр, Длина),
    Запас is Ширина - Длина,
    Сырое is Запас * Запас,
    штраф(Режим, множитель, Множ),
    Плох is Сырое * Множ,
    причины(Стр, Хвост, Режим, Крит, Линг, Пункт, Причины),
    Типо = Плох.

причины(Стр, Хвост, Режим, Крит, Линг, Пункт, Причины) :-
    findall(причина(Тип, Комп, Знач), причина(Стр, Хвост, Режим, Тип, Комп, Знач), Причины),
    сумма(Причины, крит, Крит),
    сумма(Причины, линг, Линг),
    сумма(Причины, пункт, Пункт).

сумма([], _, 0).

